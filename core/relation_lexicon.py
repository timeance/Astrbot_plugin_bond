def describe(state) -> RelationDescription:
    """state 由 RelationResolver 的 RelationState 校验，分档后常数次查表。"""
    values = (state.familiarity, state.affinity, state.trust)
    # 负边界保持旧合同：-40 属于戒备/疏远；中间零值属于中档。
    bands = tuple(
        0 if dimension and value <= edges[0] else bisect_right(edges, value)
        for dimension, (value, edges) in enumerate(zip(values, BAND_EDGES))
    )
    key = CELLS[bands[0]][bands[1]][bands[2]]
    for candidate, lo, hi, a_band, t_band, a_min in DISPLAY_VARIANTS:
        if (
            lo <= state.familiarity < hi
            and bands[1:] == (a_band, t_band)
            and state.affinity >= a_min
        ):
            key = candidate
            break
    title, meaning = TERMS[key]
    labels = tuple(options[band] for options, band in zip(BAND_LABELS, bands))
    return RelationDescription(key, title, meaning, bands, labels)
