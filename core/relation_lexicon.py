@dataclass(frozen=True)
class RelationDescription:
    key: str
    title: str
    meaning: str
    bands: tuple[int, int, int]
    labels: tuple[str, ...]

    @property
    def text(self) -> str:
        if not self.bands:
            return f"{self.title}。{self.meaning}"
        facts = "；".join(
            f"{name}：{label}"
            for name, label in zip(("熟悉程度", "亲近程度", "信任态度"), self.labels)
        )
        return f"{self.title}。{self.meaning}\n{facts}。"


